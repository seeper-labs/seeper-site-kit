import { readFile, writeFile, mkdir, access } from "node:fs/promises";
import { join } from "node:path";
import { spawn } from "node:child_process";
import { readKitConfig } from "./config.mjs";

const KIT = new URL("..", import.meta.url);
const MARKER = "<!--gate:error-->";

function sh(cmd, cwd) {
  return new Promise((resolve, reject) => {
    const p = spawn(cmd, { cwd, shell: true, stdio: "inherit" });
    p.on("error", reject);
    p.on("exit", (code) => (code === 0 ? resolve() : reject(new Error(`site build "${cmd}" exited with ${code}`))));
  });
}

export async function writeMiddleware(cwd, cfg = { bearerPaths: [], publicImages: [] }) {
  const loginPath = join(cwd, "gate", "login.html");
  try { await access(loginPath); } catch { throw new Error("gate/login.html is missing: every site needs its own login page"); }
  const login = await readFile(loginPath, "utf8");
  if (!login.includes(MARKER)) throw new Error(`gate/login.html must contain ${MARKER} where the error message goes`);
  const version = JSON.parse(await readFile(new URL("package.json", KIT), "utf8")).version;
  const gate = await readFile(new URL("src/gate.js", KIT), "utf8");
  const out = [
    `// Generated by site-kit build ${version}. Do not edit; add functions/_middleware.js to .gitignore.`,
    gate,
    `const LOGIN_HTML = ${JSON.stringify(login)};`,
    `const BEARER_PATHS = ${JSON.stringify(cfg.bearerPaths || [])};`,
    `const PUBLIC_IMAGES = ${JSON.stringify(cfg.publicImages || [])};`,
    `export const onRequest = ({ request, env, next }) => handle(request, env, next, LOGIN_HTML, { bearerPaths: BEARER_PATHS, publicImages: PUBLIC_IMAGES });`,
    "",
  ].join("\n");
  await mkdir(join(cwd, "functions"), { recursive: true });
  const path = join(cwd, "functions", "_middleware.js");
  await writeFile(path, out);
  return path;
}

export async function run(cwd) {
  const cfg = await readKitConfig(cwd);
  await sh(cfg.build, cwd);
  const path = await writeMiddleware(cwd, cfg);
  console.log(`site-kit build: site built, gate written to ${path.slice(cwd.length + 1)}`);
  return 0;
}
