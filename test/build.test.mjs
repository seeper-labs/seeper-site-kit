import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, mkdir, writeFile, readFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { run, writeMiddleware } from "../src/build.mjs";

async function site({ build = "mkdir -p site && echo hi > site/index.html", login = "<p>L<!--gate:error--></p>" } = {}) {
  const dir = await mkdtemp(join(tmpdir(), "kit-build-"));
  await writeFile(join(dir, "package.json"), JSON.stringify({ kit: { build } }));
  if (login !== null) { await mkdir(join(dir, "gate")); await writeFile(join(dir, "gate", "login.html"), login); }
  return dir;
}

test("runs the site build, then writes a working middleware", async () => {
  const dir = await site();
  assert.equal(await run(dir), 0);
  assert.equal(await readFile(join(dir, "site", "index.html"), "utf8"), "hi\n");
  const mw = await readFile(join(dir, "functions", "_middleware.js"), "utf8");
  assert.match(mw, /^\/\/ Generated by site-kit build/);
  const mod = await import(pathToFileURL(join(dir, "functions", "_middleware.js")).href);
  const r = await mod.onRequest({ request: new Request("https://x.test/"), env: {}, next: () => new Response("SITE") });
  assert.equal(r.status, 503);
});

test("the login page is inlined and served", async () => {
  const dir = await site({ login: "<p>Seeper `${x}` \\ login<!--gate:error--></p>" });
  await run(dir);
  const mod = await import(pathToFileURL(join(dir, "functions", "_middleware.js")).href);
  const r = await mod.onRequest({ request: new Request("http://localhost:8788/"), env: { SITE_GATE_DEV_PASSWORD: "d" }, next: () => new Response("SITE") });
  assert.equal(await r.text(), "<p>Seeper `${x}` \\ login</p>");
});

test("missing gate/login.html fails and names the file", async () => {
  const dir = await site({ login: null });
  await assert.rejects(writeMiddleware(dir), /gate\/login\.html/);
});

test("a login page without the error marker fails", async () => {
  const dir = await site({ login: "<p>no marker</p>" });
  await assert.rejects(writeMiddleware(dir), /<!--gate:error-->/);
});

test("reports a failing site build", async () => {
  const dir = await site({ build: "exit 7" });
  await assert.rejects(run(dir), /"exit 7" exited with 7/);
});
