import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, mkdir, writeFile, readFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { run, writeMiddleware } from "../src/build.mjs";
import { readKitConfig, KitConfigError } from "../src/config.mjs";

async function site({ build = "mkdir -p site && echo hi > site/index.html", login = "<p>L<!--gate:error--></p>", kit = { build } } = {}) {
  const dir = await mkdtemp(join(tmpdir(), "kit-build-"));
  await writeFile(join(dir, "package.json"), JSON.stringify({ kit }));
  if (login !== null) { await mkdir(join(dir, "gate")); await writeFile(join(dir, "gate", "login.html"), login); }
  return dir;
}

test("runs the site build, then writes a working middleware", async () => {
  const dir = await site();
  assert.equal(await run(dir), 0);
  assert.equal(await readFile(join(dir, "site", "index.html"), "utf8"), "hi\n");
  const mw = await readFile(join(dir, "functions", "_middleware.js"), "utf8");
  assert.match(mw, /^\/\/ Generated by site-kit build/);
  const mod = await import(pathToFileURL(join(dir, "functions", "_middleware.js")).href);
  const r = await mod.onRequest({ request: new Request("https://x.test/"), env: {}, next: () => new Response("SITE") });
  assert.equal(r.status, 503);
});

test("the login page is inlined and served", async () => {
  const dir = await site({ login: "<p>Seeper `${x}` \\ login<!--gate:error--></p>" });
  await run(dir);
  const mod = await import(pathToFileURL(join(dir, "functions", "_middleware.js")).href);
  const r = await mod.onRequest({ request: new Request("http://localhost:8788/"), env: { SITE_GATE_DEV_PASSWORD: "d" }, next: () => new Response("SITE") });
  assert.equal(await r.text(), "<p>Seeper `${x}` \\ login</p>");
});

test("missing gate/login.html fails and names the file", async () => {
  const dir = await site({ login: null });
  await assert.rejects(writeMiddleware(dir), /gate\/login\.html/);
});

test("a login page without the error marker fails", async () => {
  const dir = await site({ login: "<p>no marker</p>" });
  await assert.rejects(writeMiddleware(dir), /<!--gate:error-->/);
});

test("reports a failing site build", async () => {
  const dir = await site({ build: "exit 7" });
  await assert.rejects(run(dir), /"exit 7" exited with 7/);
});

test("kit.bearerPaths is read and defaults to none", async () => {
  const dir = await site({ kit: { build: "true" } });
  assert.deepEqual((await readKitConfig(dir)).bearerPaths, []);
  const dir2 = await site({ kit: { build: "true", bearerPaths: ["/api/comments"] } });
  assert.deepEqual((await readKitConfig(dir2)).bearerPaths, ["/api/comments"]);
});

test("kit.bearerPaths refuses the root, relative paths, dot segments and encodings", async () => {
  for (const bad of [["/"], ["api/comments"], ["/api/../x"], ["/api/%2fx"], [""], [3], "/api"]) {
    const dir = await site({ kit: { build: "true", bearerPaths: bad } });
    await assert.rejects(readKitConfig(dir), KitConfigError, JSON.stringify(bad));
  }
});

test("build writes the bearer paths into the middleware", async () => {
  const dir = await site({ kit: { build: "true", bearerPaths: ["/api/comments"] } });
  await run(dir);
  const mw = await readFile(join(dir, "functions", "_middleware.js"), "utf8");
  assert.match(mw, /const BEARER_PATHS = \["\/api\/comments"\];/);
  assert.match(mw, /handle\(request, env, next, LOGIN_HTML, \{ bearerPaths: BEARER_PATHS, publicImages: PUBLIC_IMAGES \}\)/);
});

test("kit.publicImages is read, defaults to none and is written into the middleware", async () => {
  assert.deepEqual((await readKitConfig(await site({ kit: { build: "true" } }))).publicImages, []);
  const dir = await site({ kit: { build: "true", publicImages: ["/og.png"] } });
  assert.deepEqual((await readKitConfig(dir)).publicImages, ["/og.png"]);
  await run(dir);
  const mw = await readFile(join(dir, "functions", "_middleware.js"), "utf8");
  assert.match(mw, /const PUBLIC_IMAGES = \["\/og.png"\];/);
});

test("kit.publicImages refuses pages, directories, dot segments and encodings", async () => {
  for (const bad of [["/"], ["/index.html"], ["og.png"], ["/a/../og.png"], ["/%6fg.png"], ["/og.svg"], ["/og.png/"], [3], "/og.png"]) {
    const dir = await site({ kit: { build: "true", publicImages: bad } });
    await assert.rejects(readKitConfig(dir), KitConfigError, JSON.stringify(bad));
  }
});
